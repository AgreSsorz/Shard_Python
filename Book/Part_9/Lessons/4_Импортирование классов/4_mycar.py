## Импортирование классов ##
"""
С добавлением новой функциональности в классы файлы могут стать слишком
длинными, даже при правильном использовании наследования.

Для этого Python позволяет хранить классы в модулях и импортировать
нужные классы в основную программу.
"""

### Ипортирование одного класса ###
"""
Начнём с создания модуля, содержащего только класс Car.
Создадим отдельный модуль с названием class_car.py и поместим туда класс Car.

Теперь мы можем импортировать созданный класс из созданного модуля:
"""
from class_car import Car

my_new_car = Car('audi', 'a4', 2019)
print(my_new_car.get_descriptive_name())

my_new_car.odometer_reading = 23
my_new_car.read_odometer()
print()

### Хранение нескольких классов в модуле ###
"""
В одном модуле можно хранить сколько угодно классов, хотя все эти классы
должны быть каким-то образом связаны друг с другом.
Оба класса, Battery и ElectricCar, используются для представления автомобилей,
поэтому мы добавим их в тот же отдельный модуль для последующего импорта.
"""
from class_car import ElectricCar

my_tesla = ElectricCar('tesla', 'model s', 2019)

print(my_tesla.get_descriptive_name())
my_tesla.battery.describe_battery()
print()

### Импортирование нескольких классов из модуля ###
"""
В файл программы можно импортировать столько классов, сколько потребуется.
Если захочется создать разные виды автомобилей, то надо импортировать их классы.
"""
from class_car import Car, ElectricCar

my_beetle = Car('volkswagen', 'beetle', 2019)
print(my_beetle.get_descriptive_name())

my_tesla = ElectricCar('tesla', 'model s', 2019)
print(my_tesla.get_descriptive_name())
print()

### Импортирование всего модуля ###
"""
Также можно импортировать весь модуль, чтобы затем обращаться к нужным классам
с использованием точечной записи.
Так как каждый вызов, создающий экземпляр класса, включает имя модуля,
то в программе не будет конфликтов с именами, используемыми в текущем файле.
"""
import class_car

my_beetle = Car('volkswagen', 'beetle', 2019)
print(my_beetle.get_descriptive_name())

my_tesla = ElectricCar('tesla', 'model s', 2019)
print(my_tesla.get_descriptive_name())
print()

### Импортирование всех классов из модуля ###
"""
Для импортирования всех классов из модуля используется следующий синтаксис:
from имя_модуля import *

Использовать этот способ не рекомендуется по причине конфликтов имён в файле,
а также могут возникнуть и более коварные ошибки, на решения которых
уйдёт достаточно времени.
"""

### Импортирование модуля в модуль ###
"""
Иногда классы приходится распределять по нескольким модулям, чтобы избежать
чрезмерного разрастания одного файла и хранение несвязанных классов в одном
модуле.
При хранении классов в нескольких модулях, может оказаться, что один класс
зависим от другого.

Допустим, класс Car хранится в одном модуле,
а классы ElectricCar и Battery в другом.
Тогда синтаксис будет выглядеть примерно так:
from class_car import Car
from electric_car import ElectricCar
"""

