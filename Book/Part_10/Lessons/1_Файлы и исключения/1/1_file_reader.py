### Чтение из файла ###
"""
Гигантские объёмы данных доступны в текстовых файлах.
В них могут храниться погодные данные, социально-экономическая информация,
литературные произведения и многое другое.

Чтение из файла особенно актуально для приложений, предназначенных
для анализа данных, но оно также может пригодиться в любой ситуации,
требующей анализа или изменения информации, хранящейся в файле.

Например, программа может читать содержимое текстового файла и переписывать его
с форматированием, рассчитанным на отображение информации в браузере.

Работа с информацией в текстовом файле начинается с чтения данных в память.
Мы можем прочитать всё содержимое файла или же читать данные по строкам.
"""

### Чтение всего файла ###
"""
Для начала нам понадобится файл с несколькими строками текста.
Пусть это будет файл с числом Пи с точностью до 30 знаков, по 10 на строку:
pi_digits.txt

Следующая программа открывает этот файл, читает его и выводит содержимое
на экран:
"""
with open('pi_digits.txt') as file_object:
	contents = file_object.read()
print(contents)
