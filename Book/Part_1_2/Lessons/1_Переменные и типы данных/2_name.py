## Изменение регистра символов в строках
# создаём переменную name со строкой
name = "ada lovelace"
# выводим name с методом title(), который меняет первые буквы на большие
print(name.title())
# title() не требует данных в скобках, поэтому они пусты

name_other = name
# метод upper() делает все буквы большими
print(name.upper())
# метод lower() делает все буквы маленькими
print(name.lower())
